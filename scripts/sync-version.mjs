// One version, three places: packages/cli/package.json is the source; src/version.ts (inlined into
// the bundle, which has no package.json next to it) and skills/ttt/SKILL.md must match. `--write`
// rewrites the two derived places; without it, a mismatch fails the check.
import assert from "node:assert/strict"
import { readFile, writeFile } from "node:fs/promises"

const write = process.argv.includes("--write")
const pkg = JSON.parse(await readFile(new URL("../packages/cli/package.json", import.meta.url), "utf8"))

const versionFile = new URL("../packages/cli/src/version.ts", import.meta.url)
const versionSource = `// Generated by scripts/sync-version.mjs from packages/cli/package.json; \`pnpm run check\` asserts it matches.\nexport const TTT_VERSION = ${JSON.stringify(pkg.version)}\n`
if (write) await writeFile(versionFile, versionSource)
assert.equal(await readFile(versionFile, "utf8"), versionSource, "packages/cli/src/version.ts is stale; run: node scripts/sync-version.mjs --write")

const skillFile = new URL("../skills/ttt/SKILL.md", import.meta.url)
const skill = await readFile(skillFile, "utf8")
const [frontmatter, ...rest] = skill.split("\n---")
const match = /^version:\s*(\S+)\s*$/m.exec(frontmatter)
assert.ok(match, "skills/ttt/SKILL.md frontmatter needs a version: line")
if (write && match[1] !== pkg.version) {
  await writeFile(skillFile, [frontmatter.replace(/^version:.*$/m, `version: ${pkg.version}`), ...rest].join("\n---"))
} else {
  assert.equal(match[1], pkg.version, `skills/ttt/SKILL.md version ${match[1]} must equal packages/cli version ${pkg.version}; run: node scripts/sync-version.mjs --write`)
}
